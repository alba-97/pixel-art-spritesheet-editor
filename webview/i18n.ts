const dictionaries: Record<UILanguage, Record<MessageKey, string>> = { en, es };

export function translate(
  language: UILanguage,
  key: MessageKey,
  values?: Record<string, string | number>
): string {
  let text: string = dictionaries[language][key];
  if (values) {
    for (const [name, value] of Object.entries(values)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function isMessageKey(value: string | undefined): value is MessageKey {
  return value !== undefined && Object.prototype.hasOwnProperty.call(en, value);
}

export function applyStaticTranslations(language: UILanguage): void {
  document.documentElement.lang = language;
  const textElements = document.querySelectorAll<HTMLElement>('[data-i18n]');
  for (const element of textElements) {
    const key = element.dataset.i18n;
    if (isMessageKey(key)) {
      element.textContent = translate(language, key);
    }
  }
  const titleElements = document.querySelectorAll<HTMLElement>('[data-i18n-title]');
  for (const element of titleElements) {
    const key = element.dataset.i18nTitle;
    if (isMessageKey(key)) {
      element.title = translate(language, key);
    }
  }
}
